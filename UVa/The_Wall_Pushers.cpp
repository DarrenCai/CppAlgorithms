short h(short r, short c) {
    for (short i=0; i<16; ++i) {
        short rr = t[r][c][i][0], cc = t[r][c][i][1], n = 13*rr+cc;
        if ((rr==0 && !g[n]) || (cc==0 && !g[n+6]) || (cc==5 && !g[n+7]) || (rr==3 && !g[n+13]))
            return 1 + dis(rr,r) + dis(cc,c);
    }
    return 10;
}

bool IDAStar(short r, short c, short pre = -1, short step=0) {
    short n = 13*r+c;
    if (step == depth-1) {
        if (r==0 && !g[n]) {
            path[step] = 'N'; return true;
        }
        if (c==0 && !g[n+6]) {
            path[step] = 'W'; return true;
        }
        if (c==5 && !g[n+7]) {
            path[step] = 'E'; return true;
        }
        if (r==3 && !g[n+13]) {
            path[step] = 'S'; return true;
        }
    }
    if (step < depth) {
        if (pre!=3 && r && (!g[n] || !g[n-13])) {
            bool a = g[n], b = g[n-13]; path[step] = 'N';
            if (g[n]) g[n-13] = true, g[n] = false;
            if (step + 1 + h(r-1, c) <= depth && IDAStar(r-1, c, 0, step+1)) return true;
            g[n] = a, g[n-13] = b;
        }
        if (pre!=2 && c && (!g[n+6] || !g[n+5])) {
            bool a = g[n+6], b = g[n+5]; path[step] = 'W';
            if (g[n+6]) g[n+5] = true, g[n+6] = false;
            if (step + 1 + h(r, c-1) <= depth && IDAStar(r, c-1, 1, step+1)) return true;
            g[n+6] = a, g[n+5] = b;
        }
        if (pre!=1 && c<5 && (!g[n+7] || !g[n+8])) {
            bool a = g[n+7], b = g[n+8]; path[step] = 'E';
            if (g[n+7]) g[n+8] = true, g[n+7] = false;
            if (step + 1 + h(r, c+1) <= depth && IDAStar(r, c+1, 2, step+1)) return true;
            g[n+7] = a, g[n+8] = b;
        }
        if (pre!=0 && r<3 && (!g[n+13] || !g[n+26])) {
            bool a = g[n+13], b = g[n+26]; path[step] = 'S';
            if (g[n+13]) g[n+26] = true, g[n+13] = false;
            if (step + 1 + h(r+1, c) <= depth && IDAStar(r+1, c, 3, step+1)) return true;
            g[n+13] = a, g[n+26] = b;
        }
    }
    return false;
}

